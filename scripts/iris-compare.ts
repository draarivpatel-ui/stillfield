// Screens every synthetic proof clip (encoded as H.264) with Stillfield and with EA IRIS, and writes
// docs/IRIS-COMPARISON.md. Usage: node scripts/iris-compare.ts <path to IrisApp> <work dir>
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { CLIPS, generateClip } from '../src/core/index.ts';
import { encodeVideo } from '../src/node/ffmpeg.ts';
import { screen } from '../src/node/screen.ts';

const [irisBin, work] = process.argv.slice(2).map((p) => resolve(p));
if (!irisBin || !work) throw new Error('usage: node scripts/iris-compare.ts <IrisApp> <work dir>');
mkdirSync(work, { recursive: true });
copyFileSync(join(dirname(irisBin), 'appsettings.json'), join(work, 'appsettings.json'));

function iris(file: string): { result: string; detail: string } {
  const r = spawnSync(irisBin, ['-v', file, '-j', '1'], { cwd: work, encoding: 'utf8' });
  const name = file.split('/').pop()!;
  const out = join(work, 'Results', name, 'result.json');
  if (r.status !== 0 || !existsSync(out)) return { result: 'error', detail: (r.stderr || r.stdout).slice(-200) };
  const j = JSON.parse(readFileSync(out, 'utf8'));
  const map: Record<string, string> = { Fail: 'fail', Pass: 'pass', PassWithWarning: 'warn' };
  return { result: map[j.OverallResult] ?? j.OverallResult, detail: (j.Results ?? []).join(', ') };
}

const rows: string[] = [];
let agreeFrame = 0;
let agreeWcag = 0;
let n = 0;
for (const spec of CLIPS) {
  const file = join(work, `${spec.name}.mp4`);
  if (!existsSync(file)) {
    const enc = encodeVideo(file, spec.width, spec.height, spec.fps);
    for (const f of generateClip(spec)) await enc.write(f.data);
    await enc.close();
  }
  const wcag = await screen(file, { timeline: false });
  const frame = await screen(file, { timeline: false, areaRule: 'frame' });
  const ir = iris(file);
  // IRIS has no WCAG verdict of its own; compare its overall result with Stillfield's 2.3.1 result in frame mode,
  // and separately with Stillfield's default (wcag) verdict
  const irisFail = ir.result === 'fail';
  const sameFrame = irisFail === (frame.wcag231 === 'fail');
  const sameWcag = irisFail === (wcag.wcag231 === 'fail');
  n++;
  if (sameFrame) agreeFrame++;
  if (sameWcag) agreeWcag++;
  rows.push(
    `| ${spec.name} | ${spec.expect ? `${spec.expect.wcag231} / ${spec.expect.verdict}` : 'not asserted'} | ${wcag.wcag231} / ${wcag.verdict} | ${frame.wcag231} / ${frame.verdict} | ${ir.result}${ir.detail ? ` (${ir.detail})` : ''} | ${sameFrame ? 'yes' : '**no**'} |`,
  );
  console.log(spec.name, wcag.verdict, frame.verdict, ir.result, ir.detail);
}
const irisVersion = spawnSync('git', ['-C', join(dirname(irisBin), '..', '..'), 'log', '-1', '--format=%H %cs'], { encoding: 'utf8' }).stdout.trim();
const md = `# Stillfield and EA IRIS on the synthetic proof set

Generated by \`node scripts/iris-compare.ts <IrisApp> <work dir>\` on ${new Date().toISOString().slice(0, 10)}.
IRIS commit ${irisVersion || '(unknown)'}, built from source with its default \`appsettings.json\` (area 0.25 of the
frame, pattern detection off). Each clip is generated by \`src/core/synth.ts\`, encoded to H.264 yuv420p by ffmpeg, and
the same file is given to both tools. Stillfield screens video full screen at 1024 x 768.

Columns: expected result (WCAG 2.3.1 / verdict) from the clip definition; Stillfield with its default area rule
(\`wcag\`, 25% of any 341 x 256 CSS px field); Stillfield with \`--area frame\` (25% of the frame, IRIS's rule); IRIS's
overall result. "Agree" compares IRIS fail or not with Stillfield \`--area frame\` 2.3.1 fail or not.

| Clip | Expected | Stillfield (wcag) | Stillfield (frame) | IRIS | Agree |
| --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

Agreement on fail or not: ${agreeFrame} of ${n} clips with \`--area frame\`, ${agreeWcag} of ${n} with the default area rule.

Where they differ on fail or not, and why (see SPEC.md sections 5 and 8):
- \`warn-extended-2.5hz\`: IRIS turns sustained flashing (4 to 6 transitions a second for 4 s within 5 s) into a
  failure ("extended failure"). Stillfield reports it as a warning and keeps the WCAG 2.3.1 result a pass, because
  WCAG has no such rule. Both tools flag it.
- \`fail-counterphase-halves\`: IRIS averages luminance over the whole frame, and two halves flashing in counter
  phase keep that mean flat, so IRIS passes it. Stillfield tracks each 2 x 2 CSS px cell and fails it.
- \`char-pan-stripes\` and \`char-text-scroll\` (characterisation clips, no expected answer): fast motion of high
  contrast detail. Stillfield counts each cell's luminance changes and flags both; IRIS's frame mean stays flat and
  passes both. This is Stillfield's main known source of false alarms (README, Limits).

Other differences that do not change fail or not here:
- IRIS also marks 4 or more transitions a second as "pass with warning" (\`pass-full-2hz\`); Stillfield warns only at
  3 flashes a second, near the area limit, or for sustained flashing.
- IRIS's red test is the older (R - G - B) x 320 value; Stillfield uses the WCAG 2.2 u'v' definition. Both fail
  \`fail-red-4hz\`.
- Under the default WCAG area rule, Stillfield also fails \`borderline-area-over\`, \`fail-counterphase\` and
  \`fail-half-field\`, which are under 25% of the frame. That is the difference between the area rules, not between
  the detectors.
`;
writeFileSync(join(import.meta.dirname, '..', 'docs', 'IRIS-COMPARISON.md'), md);
console.log(`agree (frame) ${agreeFrame}/${n}, agree (wcag) ${agreeWcag}/${n}`);
